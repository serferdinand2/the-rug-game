// The art preview sheet: every scene part on its own and every drawn asset, for review (npm run art).
import { writeFile } from 'node:fs/promises';
import { realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createCanvas, outline, seededRandom, toSvg } from './painter.js';
import { PALETTE } from './palette.js';
import { drawSky } from './parts/sky.js';
import { drawSea } from './parts/sea.js';
import { drawTerrain } from './parts/terrain.js';
import { drawBuilding } from './parts/buildings.js';
import { drawFigure } from './parts/figures.js';
import { ASSETS } from './catalog.js';
import { listDrawingIds, renderAsset } from './build.mjs';

/** @typedef {import('./painter.js').Canvas} Canvas */

/** Where the sheet is written. It is git-ignored and never served. */
const PREVIEW_FILE = fileURLToPath(
	new URL('../docs/art/preview.html', import.meta.url)
);

/**
 * One sample per scene part, each alone on a 64×64 canvas.
 * Foreground parts get the outline pass, as they would in a scene.
 * @type {{ label: string, draw: () => Canvas }[]}
 */
const PART_SAMPLES = [
	...['night', 'day', 'dusk'].map((time) => ({
		label: `sky: ${time}`,
		draw: () => {
			const c = createCanvas(64, 64);
			drawSky(c, {
				time: /** @type {'night' | 'day' | 'dusk'} */ (time),
				horizon: 63,
				random: seededRandom(7),
				sparkles: [[12, 8]],
				moon: { x: 46, y: 14 },
			});
			return c;
		},
	})),
	...['night', 'day'].map((time) => ({
		label: `sea: ${time}`,
		draw: () => {
			const c = createCanvas(64, 64);
			drawSea(c, {
				time: /** @type {'night' | 'day'} */ (time),
				top: 0,
				random: seededRandom(7),
			});
			return c;
		},
	})),
	...['forest', 'mountain', 'desert', 'grassland'].map((kind) => ({
		label: `terrain: ${kind}`,
		draw: () => {
			const c = createCanvas(64, 64);
			drawTerrain(c, {
				kind: /** @type {'forest' | 'mountain' | 'desert' | 'grassland'} */ (
					kind
				),
				top: 40,
				random: seededRandom(7),
			});
			return c;
		},
	})),
	...['house', 'tower', 'wall'].map((kind) => ({
		label: `building: ${kind}`,
		draw: () => {
			const c = createCanvas(64, 64);
			drawBuilding(c, {
				kind: /** @type {'house' | 'tower' | 'wall'} */ (kind),
				x: 22,
				y: 58,
			});
			outline(c, PALETTE.ink);
			return c;
		},
	})),
	{
		label: 'figure',
		draw: () => {
			const c = createCanvas(64, 64);
			drawFigure(c, { x: 25, y: 58 });
			drawFigure(c, {
				x: 33,
				y: 58,
				facing: 'left',
				clothes: PALETTE.roofLight,
			});
			outline(c, PALETTE.ink);
			return c;
		},
	},
];

/**
 * Escapes text for HTML.
 * @param {string} text
 * @returns {string}
 */
function escape(text) {
	return text
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}

/**
 * One tile on the sheet: the picture at 1× and 4×, with its label.
 * @param {string} label
 * @param {string} svg
 * @param {string} [detail]
 * @returns {string}
 */
function tile(label, svg, detail = '') {
	const sized = (/** @type {number} */ scale) =>
		svg.replace(
			'<svg ',
			`<svg width="${64 * scale}" height="${64 * scale}" role="img" aria-label="${escape(label)}" `
		);
	return `<figure>${sized(4)}${sized(1)}<figcaption><b>${escape(label)}</b>${detail ? `<span>${escape(detail)}</span>` : ''}</figcaption></figure>`;
}

/**
 * Builds the review sheet.
 * @returns {Promise<string>} A self-contained HTML page.
 */
export async function buildPreview() {
	const parts = PART_SAMPLES.map((sample) =>
		tile(sample.label, toSvg(sample.draw()))
	);
	const names = new Map(ASSETS.map((asset) => [asset.id, asset.name]));
	const drawings = [];
	for (const id of await listDrawingIds()) {
		drawings.push(tile(id, await renderAsset(id), names.get(id)));
	}
	return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Art preview</title>
<style>
body{margin:0;padding:24px;background:#18121f;color:#efe6d2;font:14px/1.4 ui-monospace,monospace}
h1{font-size:20px;margin:0 0 4px}h2{font-size:16px;margin:28px 0 12px;color:#f2d58c}
p{margin:0;color:#c9bfe0}
.grid{display:flex;flex-wrap:wrap;gap:16px}
figure{margin:0;padding:10px;background:#2b2142;border-radius:6px;display:grid;grid-template-columns:auto auto;gap:10px;align-items:end}
svg{display:block;image-rendering:pixelated;background:repeating-conic-gradient(#3a2c55 0 25%,#30233c 0 50%) 0 0/16px 16px}
figcaption{grid-column:1/-1;display:flex;flex-direction:column}figcaption span{color:#a99cc4}
</style>
</head>
<body>
<h1>Art preview</h1>
<p>Generated by npm run art. Scene parts are shown alone; foreground parts carry the outline pass.</p>
<h2>Scene parts</h2>
<div class="grid">${parts.join('')}</div>
<h2>Drawn assets (${drawings.length})</h2>
<div class="grid">${drawings.join('')}</div>
</body>
</html>
`;
}

// Write the sheet only when this file is the entry point, not when tests import it.
if (
	process.argv[1] &&
	realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	await writeFile(PREVIEW_FILE, await buildPreview());
	console.log('art: wrote docs/art/preview.html');
}
