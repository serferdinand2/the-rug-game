export function draw() {
	const canvas = createCanvas(425, 298);
	for (let y = 0; y < ROWS.length; y++) {
		let x = 0;
		for (const segment of ROWS[y].split(' ')) {
			const [widthText, index] = segment.split(':');
			const width = Number(widthText);
			if (index !== '-') {
				const [color, alpha] = PALETTE[Number(index)];
				rect(canvas, x, y, width, 1, color);
				if (alpha !== 1) {
					canvas.alpha ??= new Array(canvas.w * canvas.h).fill(1);
					canvas.alpha.fill(
						alpha,
						y * canvas.w + x,
						y * canvas.w + x + width
					);
				}
			}
			x += width;
		}
	}
	return canvas;
}
