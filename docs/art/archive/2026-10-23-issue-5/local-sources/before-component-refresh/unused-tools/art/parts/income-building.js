/** Draws one income-building sprite at its native 32×32 size. @param {IncomeBuilding} type @returns {Canvas} */
export function drawIncomeBuilding(type) {
	const sprite = SPRITES[type];
	if (!sprite) throw new Error(`Unknown income building: ${type}`);
	const canvas = createCanvas(32, 32);
	for (let y = 0; y < sprite.rows.length; y++) {
		for (let x = 0; x < sprite.rows[y].length; x++) {
			const colorIndex = PIXEL_ALPHABET.indexOf(sprite.rows[y][x]);
			if (colorIndex >= 0) set(canvas, x, y, sprite.colors[colorIndex]);
		}
	}
	return canvas;
}
